"""Write hpack_huffman.h, HPACK's static Huffman code (RFC 7541, Appendix B),
measured from the system's libnghttp2 rather than typed in.

Each symbol's code length comes from how many bytes libnghttp2's encoder
needs for that symbol followed by runs of 'a'; the code is canonical, so the
lengths fix the codes. The result is then checked byte for byte against
libnghttp2's own Huffman output on random strings.

    python3 gen_hpack_huffman.py > hpack_huffman.h
"""

import ctypes
import random
import sys

lib = ctypes.CDLL("libnghttp2.so.14")


class NV(ctypes.Structure):
    _fields_ = [("name", ctypes.c_char_p), ("value", ctypes.c_void_p), ("namelen", ctypes.c_size_t), ("valuelen", ctypes.c_size_t), ("flags", ctypes.c_uint8)]


lib.nghttp2_hd_deflate_new.argtypes = [ctypes.POINTER(ctypes.c_void_p), ctypes.c_size_t]
lib.nghttp2_hd_deflate_hd.argtypes = [ctypes.c_void_p, ctypes.c_char_p, ctypes.c_size_t, ctypes.POINTER(NV), ctypes.c_size_t]
lib.nghttp2_hd_deflate_hd.restype = ctypes.c_ssize_t
lib.nghttp2_hd_deflate_del.argtypes = [ctypes.c_void_p]


def value_string(value):
    """(huffman?, bytes) of `value` as libnghttp2 encodes it in a never-indexed literal."""
    d = ctypes.c_void_p()
    assert lib.nghttp2_hd_deflate_new(ctypes.byref(d), 0) == 0
    buf = ctypes.create_string_buffer(4096)
    v = ctypes.create_string_buffer(value, len(value))
    nv = NV(b"x-k", ctypes.cast(v, ctypes.c_void_p), 3, len(value), 1)
    n = lib.nghttp2_hd_deflate_hd(d, buf, 4096, ctypes.byref(nv), 1)
    block = buf.raw[:n]
    lib.nghttp2_hd_deflate_del(d)
    if block[0] == 0x20:  # dynamic table size update
        block = block[1:]
    i = 2 + (block[1] & 0x7F)  # 0x10, then the name "x-k"
    huffman, n = block[i] >> 7, block[i] & 0x7F
    i += 1
    if n == 0x7F:
        shift = 0
        while True:
            b = block[i]
            i += 1
            n += (b & 0x7F) << shift
            shift += 7
            if not b & 0x80:
                break
    return huffman, block[i : i + n]


lengths = []
for symbol in range(256):
    fits = set(range(5, 31))
    for k in range(20, 36):  # 'a' is 5 bits, so k of them keep Huffman shorter
        huffman, data = value_string(bytes([symbol]) + b"a" * k)
        assert huffman
        fits = {n for n in fits if (n + 5 * k + 7) // 8 == len(data)}
    assert len(fits) == 1, (symbol, fits)
    lengths.append(fits.pop())
lengths.append(30)  # EOS
assert sum(2.0 ** -n for n in lengths) == 1.0

codes, code, prev = [0] * 257, 0, None
for i, s in enumerate(sorted(range(257), key=lambda s: (lengths[s], s))):
    if i:
        code = (code + 1) << (lengths[s] - prev)
    codes[s], prev = code, lengths[s]


def encode(data):
    bits = n = 0
    out = bytearray()
    for b in data:
        bits, n = (bits << lengths[b]) | codes[b], n + lengths[b]
        while n >= 8:
            n -= 8
            out.append((bits >> n) & 0xFF)
    if n:
        out.append(((bits << (8 - n)) | ((1 << (8 - n)) - 1)) & 0xFF)
    return bytes(out)


random.seed(7)
matched = 0
for t in range(3000):
    alphabet = range(256) if t % 3 == 0 else b"abcdefghijklmnopqrstuvwxyzABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789_- "
    data = bytes(random.choice(alphabet) for _ in range(random.randint(1, 80)))
    huffman, got = value_string(data)
    if huffman:
        assert got == encode(data), data
        matched += 1
assert matched > 1000

print("/* HPACK's static Huffman code (RFC 7541, Appendix B), by symbol; 256 is EOS.")
print(f" * Generated by gen_hpack_huffman.py from libnghttp2, matched on {matched} strings. */")
print("static const unsigned int hpack_codes[257] = {")
for i in range(0, 257, 8):
    print("    " + ", ".join(f"0x{c:x}" for c in codes[i : i + 8]) + ",")
print("};")
print("static const unsigned char hpack_lengths[257] = {")
for i in range(0, 257, 16):
    print("    " + ", ".join(str(n) for n in lengths[i : i + 16]) + ",")
print("};")
